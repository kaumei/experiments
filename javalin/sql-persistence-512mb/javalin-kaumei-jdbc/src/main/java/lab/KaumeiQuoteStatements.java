package lab;

import io.kaumei.jdbc.annotation.JdbcBatchUpdate;
import io.kaumei.jdbc.annotation.JdbcSelect;
import io.kaumei.jdbc.annotation.JdbcUpdate;
import io.kaumei.jdbc.runtime.JdbcBatch;

import java.math.BigDecimal;
import java.util.List;

public interface KaumeiQuoteStatements {

    @JdbcUpdate("""
            CREATE TABLE IF NOT EXISTS quotes (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                batch_seq INTEGER NOT NULL,
                cycle INTEGER NOT NULL,
                sample_index INTEGER NOT NULL,
                market_time VARCHAR(5) NOT NULL,
                symbol VARCHAR(8) NOT NULL,
                price DECIMAL(12,4) NOT NULL,
                UNIQUE(batch_seq,symbol)
            )
            """)
    void createTable();

    @JdbcUpdate("CREATE INDEX IF NOT EXISTS quotes_symbol ON quotes(symbol,id DESC)")
    void createIndex();

    @JdbcSelect("SELECT COUNT(*) FROM quotes")
    int count();

    @JdbcSelect("SELECT 1")
    int probe();

    @JdbcSelect("""
            SELECT SETTING_NAME || '=' || SETTING_VALUE
            FROM INFORMATION_SCHEMA.SETTINGS
            WHERE SETTING_NAME IN ('CACHE_SIZE','WRITE_DELAY')
            """)
    List<String> h2Settings();

    @JdbcSelect("""
            SELECT batch_seq,cycle,sample_index,market_time,symbol,price
            FROM quotes WHERE symbol=:symbol ORDER BY id DESC LIMIT :limit
            """)
    List<Quote> selectQuotes(String symbol, int limit);

    @JdbcSelect("""
            SELECT COUNT(*) AS row_count,
                   COALESCE(MAX(batch_seq),0) AS max_sequence,
                   COALESCE(SUM(price),0) AS price_sum
            FROM quotes
            """)
    QuoteState state();

    @JdbcBatchUpdate
    InsertBatch insertBatch();

    interface InsertBatch extends JdbcBatch {
        @JdbcUpdate("""
                INSERT INTO quotes(batch_seq,cycle,sample_index,market_time,symbol,price)
                VALUES(:sequence,:cycle,:sampleIndex,:marketTime,:symbol,:price)
                """)
        void insert(int sequence, int cycle, int sampleIndex, String marketTime, String symbol, BigDecimal price);
    }
}
